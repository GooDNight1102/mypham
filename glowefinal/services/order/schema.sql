-- Order Service — schema riêng {{s}}
CREATE SCHEMA IF NOT EXISTS {{s}};

CREATE TABLE IF NOT EXISTS {{s}}.orders (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           TEXT        NOT NULL UNIQUE,
  user_id        INTEGER     NOT NULL,              -- id bên User Service (không có khóa ngoại xuyên service)
  receiver_name  TEXT        NOT NULL,
  phone          TEXT        NOT NULL,
  address        TEXT        NOT NULL,
  note           TEXT,
  subtotal       BIGINT      NOT NULL,
  shipping_fee   BIGINT      NOT NULL,
  discount       BIGINT      NOT NULL DEFAULT 0,    -- số tiền giảm từ voucher
  voucher_code   TEXT,                              -- mã voucher đã áp (nếu có)
  total          BIGINT      NOT NULL,
  payment_method TEXT        NOT NULL CHECK (payment_method IN ('cod', 'card', 'ewallet')),
  payment_status TEXT        NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'paid', 'failed', 'refunded')),
  status         TEXT        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'shipping', 'completed', 'cancelled')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_orders_user ON {{s}}.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON {{s}}.orders(status);

-- Kho voucher: admin tạo / khóa / giới hạn số lần dùng
CREATE TABLE IF NOT EXISTS {{s}}.vouchers (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           TEXT        NOT NULL UNIQUE,
  description    TEXT,
  type           TEXT        NOT NULL CHECK (type IN ('percent', 'fixed')),
  value          BIGINT      NOT NULL CHECK (value > 0),           -- % hoặc số tiền (VND)
  min_order      BIGINT      NOT NULL DEFAULT 0,                   -- đơn tối thiểu (tạm tính)
  max_discount   BIGINT,                                           -- trần giảm (chỉ type=percent)
  usage_limit    INTEGER,                                          -- null = không giới hạn tổng
  used_count     INTEGER     NOT NULL DEFAULT 0,
  per_user_limit INTEGER     NOT NULL DEFAULT 1,                   -- mỗi user dùng tối đa bao nhiêu lần
  starts_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  ends_at        TIMESTAMPTZ,                                      -- null = không hết hạn
  is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vouchers_code ON {{s}}.vouchers(code);

-- Lịch sử dùng voucher (1 dòng = 1 lần áp vào đơn)
CREATE TABLE IF NOT EXISTS {{s}}.voucher_usages (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  voucher_id      INTEGER     NOT NULL REFERENCES {{s}}.vouchers(id),
  user_id         INTEGER     NOT NULL,
  order_id        INTEGER     NOT NULL REFERENCES {{s}}.orders(id) ON DELETE CASCADE,
  discount_amount BIGINT      NOT NULL,
  used_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voucher_usages_user ON {{s}}.voucher_usages(user_id, voucher_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_voucher_order ON {{s}}.voucher_usages(order_id);

-- Snapshot tên + giá lúc mua: sửa giá sản phẩm không làm sai đơn cũ
CREATE TABLE IF NOT EXISTS {{s}}.order_items (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     INTEGER NOT NULL REFERENCES {{s}}.orders(id) ON DELETE CASCADE,
  product_id   INTEGER NOT NULL,
  product_name TEXT    NOT NULL,
  price        BIGINT  NOT NULL,
  quantity     INTEGER NOT NULL CHECK (quantity > 0),
  line_total   BIGINT  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_items_order ON {{s}}.order_items(order_id);

-- Thông báo cho khách: mỗi lần đơn đổi trạng thái (đặt, thanh toán, xác nhận, giao, nhận, hủy) = 1 dòng
CREATE TABLE IF NOT EXISTS {{s}}.notifications (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER     NOT NULL,
  order_id   INTEGER     NOT NULL REFERENCES {{s}}.orders(id) ON DELETE CASCADE,
  type       TEXT        NOT NULL CHECK (type IN ('placed', 'confirmed', 'payment_failed', 'shipping', 'completed', 'cancelled')),
  title      TEXT        NOT NULL,
  body       TEXT        NOT NULL,
  is_read    BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON {{s}}.notifications(user_id, created_at DESC);

-- Bổ sung cột cho CSDL đã tạo trước khi có voucher (an toàn khi chạy lại setup)
ALTER TABLE {{s}}.orders ADD COLUMN IF NOT EXISTS discount BIGINT NOT NULL DEFAULT 0;
ALTER TABLE {{s}}.orders ADD COLUMN IF NOT EXISTS voucher_code TEXT;
