-- Payment Service — schema riêng {{s}}. Mỗi lần thử thanh toán = 1 dòng (kể cả thất bại). Chỉ lưu 4 số cuối thẻ.
CREATE SCHEMA IF NOT EXISTS {{s}};

CREATE TABLE IF NOT EXISTS {{s}}.payments (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id        INTEGER     NOT NULL,                -- id bên Order Service
  user_id         INTEGER     NOT NULL,
  method          TEXT        NOT NULL CHECK (method IN ('cod', 'card', 'ewallet')),
  amount          BIGINT      NOT NULL,
  status          TEXT        NOT NULL CHECK (status IN ('success', 'failed', 'refunded')),
  transaction_ref TEXT,
  card_last4      TEXT,
  message         TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_payments_order ON {{s}}.payments(order_id);
-- Chặn thanh toán thành công 2 lần cho 1 đơn, kể cả khi bấm đồng thời
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_success ON {{s}}.payments(order_id) WHERE status = 'success';
