-- User Service — schema riêng {{s}} (PostgreSQL / Supabase)
CREATE SCHEMA IF NOT EXISTS {{s}};

CREATE TABLE IF NOT EXISTS {{s}}.users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     TEXT        NOT NULL,
  email         TEXT        NOT NULL UNIQUE,         -- luôn lưu chữ thường
  phone         TEXT        NOT NULL,
  address       TEXT,
  password_hash TEXT        NOT NULL,                -- scrypt: "salt:hash", không lưu mật khẩu thô
  role          TEXT        NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  is_active     BOOLEAN     NOT NULL DEFAULT TRUE,   -- FALSE = bị khóa
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
