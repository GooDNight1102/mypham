-- Product Service — schema riêng {{s}} (danh mục + mỹ phẩm + tồn kho)
CREATE SCHEMA IF NOT EXISTS {{s}};

CREATE TABLE IF NOT EXISTS {{s}}.categories (
  id    INTEGER PRIMARY KEY,
  name  TEXT NOT NULL,
  slug  TEXT NOT NULL UNIQUE,
  icon  TEXT NOT NULL DEFAULT '✨'
);

CREATE TABLE IF NOT EXISTS {{s}}.products (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER     NOT NULL REFERENCES {{s}}.categories(id),
  name        TEXT        NOT NULL,
  brand       TEXT        NOT NULL,
  description TEXT,
  price       BIGINT      NOT NULL CHECK (price > 0),           -- VNĐ
  old_price   BIGINT      CHECK (old_price IS NULL OR old_price > price),
  stock       INTEGER     NOT NULL DEFAULT 0 CHECK (stock >= 0),
  skin_type   TEXT,
  volume      TEXT,
  image_url   TEXT,
  search      TEXT        NOT NULL DEFAULT '',                  -- tên + thương hiệu không dấu, để tìm "kem chong nang"
  is_active   BOOLEAN     NOT NULL DEFAULT TRUE,                -- xóa mềm: FALSE = ngừng bán
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_products_brand ON {{s}}.products(brand);

